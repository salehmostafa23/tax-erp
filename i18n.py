_AR = re.compile(r'[\u0621-\u064A]')
_AR_START = re.compile(r'^[\u0621-\u064A]')
_AR_END = re.compile(r'[\u0621-\u064A]$')


def _build_pattern():
    keys = sorted(EN, key=len, reverse=True)
    parts = []
    for k in keys:
        body = re.escape(k)
        pre = r'(?<![\u0621-\u064A])' if _AR_START.match(k) else ''
        post = r'(?![\u0621-\u064A])' if _AR_END.search(k) else ''
        parts.append(pre + body + post)
    return re.compile('|'.join(parts))


_PATTERN = _build_pattern()


@lru_cache(maxsize=8192)
def translate(text):
    if not isinstance(text, str) or not text or not _AR.search(text):
        return text
    return _PATTERN.sub(lambda m: EN.get(m.group(0), m.group(0)), text)


def has_arabic(text):
    return bool(isinstance(text, str) and _AR.search(text))


def untranslated(text):
    """Return the Arabic fragments that survived translation (debug helper)."""
    out = translate(text)
    return _AR.findall(out)
